def expand_provinces(names):
    """若输入列表中包含省份名称（如'广东'、'广东省'、'浙江'），自动展开为其下的全部地级市列表。"""
    if not names:
        return []
    prov_map = {}
    for item in PROVINCE_CITY_TREE:
        p_name = item["province"]
        clean_p = p_name.rstrip("省").rstrip("市").rstrip("自治区").rstrip("回族自治区").rstrip("维吾尔自治区").rstrip("壮族自治区")
        prov_map[p_name] = item["cities"]
        prov_map[clean_p] = item["cities"]
        prov_map[clean_p + "省"] = item["cities"]

    out = []
    seen = set()
    for n in names:
        val = (n or "").strip()
        if not val:
            continue
        if val in prov_map:
            for c in prov_map[val]:
                if c not in seen:
                    seen.add(c)
                    out.append(c)
        else:
            clean_v = val.rstrip("市")
            if clean_v in prov_map:
                for c in prov_map[clean_v]:
                    if c not in seen:
                        seen.add(c)
                        out.append(c)
            elif val not in seen:
                seen.add(val)
                out.append(val)
    return out


def lookup(name, cfg=None):
    """城市名 → 城市码。优先 config 的 citycodes_extra 追加映射，再查内置表。
    找不到返回 None。支持自动剥离 '市' 后缀（如 '北京市' -> '北京'）。"""
    name = (name or "").strip()
    if not name:
        return None
    extra = {}
    if cfg:
        extra = {str(k).strip().lower(): v for k, v in (cfg.get("citycodes_extra") or {}).items()}
    table = {k.lower(): v for k, v in CITY_CODES.items()}
    clean = name.rstrip("市").strip()
    return (extra.get(name.lower()) or
            table.get(name.lower()) or
            extra.get(clean.lower()) or
            table.get(clean.lower()))


def resolve_cities(names, cfg=None):
    """批量城市名解析。若输入包含省份名称，自动展开为该省全部地级市。
    返回 (resolved, unknown)：
    resolved=[{name, code}]，unknown=[未识别的城市名]（不报错，供 Web 端提示）。"""
    expanded = expand_provinces(names)
    resolved, unknown = [], []
    for n in (expanded or []):
        code = lookup(n, cfg)
        if code:
            resolved.append({"name": (n or "").strip(), "code": code, "quota": 15})
        else:
            unknown.append((n or "").strip())
    return resolved, unknown
